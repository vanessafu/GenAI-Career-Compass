RESEARCH_FLAGS = {
    "creative_mapping_questionable",
    "electrical_group_questionable",
    "low_match_confidence",
    "potentially_unrelated_group",
}


@dataclass(frozen=True)
class ReviewDecision:
    role_id: str
    job_title: str
    domain_tags: str
    current_kldb_code: str
    current_match_title: str
    current_salary_monthly_gross_eur: int | None
    current_salary_band: str
    salary_group_code: str
    salary_source_group_title: str
    salary_selected_column: str
    match_confidence: str
    source_status: str
    sanity_status: str
    sanity_flags: tuple[str, ...]
    review_decision: str
    proposed_action: str
    proposed_kldb_code: str = ""
    proposed_match_title: str = ""
    proposed_salary_median_monthly_gross_eur: int | None = None
    proposed_salary_median_display: str = ""
    proposed_salary_band: str = ""
    proposed_salary_score: int | None = None
    proposed_match_confidence: str = ""
    override_reason: str = ""
    override_notes: str = ""
    benchmark_context: str = ""


