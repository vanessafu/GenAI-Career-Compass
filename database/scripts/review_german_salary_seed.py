#!/usr/bin/env python3
"""Create review decisions and proposed overrides for Phase 7 salary seeds.

This helper is intentionally local and non-mutating. It reads the generated
salary seed and sanity-review CSVs, classifies rows into review decisions, and
writes proposed manual overrides that can be inspected before Phase 8. It never
reads from or writes to Supabase.
"""

