def main(argv: Sequence[str] | None = None) -> int:
    parser = build_arg_parser()
    args = parser.parse_args(argv)
    if args.limit is not None and args.limit < 1:
        parser.error("--limit must be greater than zero.")
    if args.top_k < 1:
        parser.error("--top-k must be greater than zero.")

    try:
        supabase_url, service_role_key = get_required_supabase_env()
        client = SupabaseRestClient(supabase_url, service_role_key)
        client.validate_read_schema()
        roles = client.list_career_roles(role_id=args.role_id, limit=args.limit)
        if not roles:
            raise ValueError("No career_roles rows matched the requested filters.")

        kldb_rows = load_kldb_workbook(args.kldb_xlsx) if args.kldb_xlsx else []
        manual_overrides = load_manual_overrides(args.manual_overrides)
        api_salary_lookup = build_salary_lookup(no_api=args.no_api, cache_dir=args.cache_dir)
        salary_table_lookup = build_salary_table_lookup(
            salary_table_html=args.salary_table_html,
            salary_table_url=args.salary_table_url,
            fetch_salary_table=args.fetch_salary_table,
        )
        salary_lookup = CombinedSalaryLookup(api_salary_lookup, salary_table_lookup)
        result = build_salary_seed_rows(
            roles=roles,
            kldb_rows=kldb_rows,
            salary_lookup=salary_lookup,
            manual_overrides=manual_overrides,
            top_k=args.top_k,
        )
        write_csv(args.output, result.seed_rows, SEED_FIELDNAMES)
        write_csv(args.review_output, result.review_rows, REVIEW_FIELDNAMES)
        stats = summarize_run(
            roles=roles,
            kldb_rows=kldb_rows,
            result=result,
            salary_lookup=salary_lookup,
            output_path=args.output,
            review_output_path=args.review_output,
            dry_run=args.dry_run,
        )
        print_summary(stats)
        return 0
    except (FileNotFoundError, ValueError, SupabaseError, KldbWorkbookError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
