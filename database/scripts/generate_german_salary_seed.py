def collapse_spaces(value: str) -> str:
    return re.sub(r"\s+", " ", str(value or "").strip())


def dedupe_nonempty(values: Iterable[str], limit: int | None = None) -> list[str]:
    items: list[str] = []
    seen: set[str] = set()
    for value in values:
        cleaned = collapse_spaces(value)
        if not cleaned:
            continue
        key = normalize_match_text(cleaned)
        if key in seen:
            continue
        seen.add(key)
        items.append(cleaned)
        if limit is not None and len(items) >= limit:
            break
    return items


def normalize_match_text(value: str) -> str:
    text = unicodedata.normalize("NFKC", str(value or "")).casefold()
    replacements = {
        "ä": "ae",
        "ö": "oe",
        "ü": "ue",
        "ß": "ss",
        "\u00a0": " ",
        "&": " and ",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    text = re.sub(r"/\s*in\b", " in", text)
    text = re.sub(r"\b(m/w/d|w/m/d|f/m/d)\b", " ", text)
    text = re.sub(r"[^a-z0-9+#.]+", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


def clean_job_title(value: str) -> str:
    text = re.sub(r"\([^)]*\)", " ", value or "")
    text = re.sub(r"\[[^\]]*\]", " ", text)
    text = re.sub(r"\b(m/w/d|w/m/d|f/m/d)\b", " ", text, flags=re.IGNORECASE)
    text = re.sub(r"[-_/]+", " ", text)
    words = [
        word
        for word in collapse_spaces(text).split()
        if word.casefold().strip(".,") not in SENIORITY_WORDS
    ]
    return collapse_spaces(" ".join(words))


def domain_tags(value: str) -> list[str]:
    return [
        tag.strip().casefold()
        for tag in re.split(r"[,\s]+", value or "")
        if tag.strip()
    ]


def generate_search_terms(role: CareerRole) -> list[SearchTerm]:
    raw_terms: list[SearchTerm] = []

    def add(term: str, source: str) -> None:
        cleaned = collapse_spaces(term)
        if cleaned:
            raw_terms.append(SearchTerm(cleaned, source))

    add(role.job_title, "original_title")

    cleaned_title = clean_job_title(role.job_title)
    if cleaned_title and normalize_match_text(cleaned_title) != normalize_match_text(role.job_title):
        add(cleaned_title, "cleaned_title")

    normalized_title = normalize_match_text(role.job_title)
    for english_title, translated_terms in TITLE_TRANSLATIONS.items():
        if english_title in normalized_title:
            for translated_term in translated_terms:
                add(translated_term, "translated_title")

    if role.esco_title:
        add(role.esco_title, "esco_title")

    for tag in domain_tags(role.domain_tags):
        add(tag.replace("_", " "), "domain_tags")
        for fallback in DOMAIN_FALLBACKS.get(tag, ()):
            add(fallback, "domain_fallback")

    if is_likely_it_role(role.job_title) and not any(
        term.source == "domain_fallback" for term in raw_terms
    ):
        add("Softwareentwickler/in", "deterministic_it_fallback")
        add("Informatiker/in", "deterministic_it_fallback")

    return [
        SearchTerm(term, source)
        for term, source in {
            (item.term, item.source): item for item in raw_terms
        }.keys()
    ]


def is_likely_it_role(value: str) -> bool:
    normalized = normalize_match_text(value)
    return any(keyword in normalized for keyword in IT_RELATED_KEYWORDS)


def is_it_related_kldb_title(value: str) -> bool:
    padded = " " + normalize_match_text(value) + " "
    return any(keyword in padded for keyword in IT_RELATED_KEYWORDS)


def is_broad_it_title(value: str) -> bool:
    normalized = normalize_match_text(value)
    return normalized in BROAD_IT_TITLES


def is_modern_or_specialized_title(value: str) -> bool:
    normalized = normalize_match_text(value)
    return any(keyword in normalized for keyword in MODERN_SPECIALIZED_KEYWORDS)


def fuzzy_score(left: str, right: str) -> float:
    left_norm = normalize_match_text(left)
    right_norm = normalize_match_text(right)
    if not left_norm or not right_norm:
        return 0.0
    if left_norm == right_norm:
        return 100.0

    try:
        from rapidfuzz import fuzz as rapidfuzz_fuzz  # type: ignore
    except ImportError:
        rapidfuzz_fuzz = None

    if rapidfuzz_fuzz is not None:
        return float(
            max(
                rapidfuzz_fuzz.ratio(left_norm, right_norm),
                rapidfuzz_fuzz.token_sort_ratio(left_norm, right_norm),
                rapidfuzz_fuzz.partial_ratio(left_norm, right_norm) * 0.95,
            )
        )

    direct = difflib.SequenceMatcher(None, left_norm, right_norm).ratio() * 100.0
    token_sort_left = " ".join(sorted(left_norm.split()))
    token_sort_right = " ".join(sorted(right_norm.split()))
    token_sort = (
        difflib.SequenceMatcher(None, token_sort_left, token_sort_right).ratio()
        * 100.0
    )
    substring = 95.0 if left_norm in right_norm or right_norm in left_norm else 0.0
    return max(direct, token_sort, substring)


def candidate_score(
    role: CareerRole,
    term: SearchTerm,
    occupation: KldbOccupation,
) -> tuple[float, float, float, bool]:
    title_similarity = fuzzy_score(term.term, occupation.title)
    original_similarity = fuzzy_score(role.job_title, occupation.title)
    source_bonus = {
        "original_title": 5.0,
        "cleaned_title": 4.0,
        "translated_title": 4.0,
        "esco_title": 2.0,
        "domain_tags": 0.0,
        "domain_fallback": 1.0,
        "deterministic_it_fallback": 0.0,
    }.get(term.source, 0.0)
    it_related = is_it_related_kldb_title(occupation.title)
    it_bonus = 3.0 if it_related else 0.0
    final_score = min(
        100.0,
        title_similarity + source_bonus + it_bonus + (original_similarity * 0.04),
    )
    return final_score, title_similarity, original_similarity, it_related


def match_kldb_candidates(
    role: CareerRole,
    kldb_rows: Sequence[KldbOccupation] | KldbSearchIndex,
    search_terms: Sequence[SearchTerm],
    top_k: int,
) -> list[KldbCandidate]:
    if isinstance(kldb_rows, KldbSearchIndex):
        index = kldb_rows
    else:
        index = build_kldb_search_index(kldb_rows)
    if not index.occupations or not search_terms:
        return []

    candidates: list[KldbCandidate] = []
    terms_by_candidate_index = candidate_terms_by_index(index, search_terms)
    for occupation_index, candidate_terms in sorted(terms_by_candidate_index.items()):
        occupation = index.occupations[occupation_index]
        best_candidate: KldbCandidate | None = None
        for term in candidate_terms:
            score, title_similarity, original_similarity, it_related = candidate_score(
                role,
                term,
                occupation,
            )
            if best_candidate is None or score > best_candidate.score:
                best_candidate = KldbCandidate(
                    title=occupation.title,
                    kldb_code=occupation.kldb_code,
                    score=score,
                    matched_term=term.term,
                    term_source=term.source,
                    title_similarity=title_similarity,
                    original_title_similarity=original_similarity,
                    it_related=it_related,
                )
        if best_candidate and best_candidate.score >= 42.0:
            candidates.append(best_candidate)

    candidates.sort(
        key=lambda candidate: (
            -candidate.score,
            -candidate.title_similarity,
            candidate.title.casefold(),
            candidate.kldb_code,
        )
    )
    return candidates[:top_k]


def build_kldb_search_index(kldb_rows: Sequence[KldbOccupation]) -> KldbSearchIndex:
    row_indexes_by_token: dict[str, set[int]] = collections.defaultdict(set)
    it_related_indexes: set[int] = set()
    for index, occupation in enumerate(kldb_rows):
        normalized_title = normalize_match_text(occupation.title)
        for token in searchable_tokens(normalized_title):
            row_indexes_by_token[token].add(index)
        if is_it_related_kldb_title(occupation.title):
            it_related_indexes.add(index)
    return KldbSearchIndex(
        occupations=kldb_rows,
        row_indexes_by_token=dict(row_indexes_by_token),
        it_related_indexes=it_related_indexes,
    )


def candidate_terms_by_index(
    index: KldbSearchIndex,
    search_terms: Sequence[SearchTerm],
) -> dict[int, list[SearchTerm]]:
    terms_by_index: dict[int, list[SearchTerm]] = collections.defaultdict(list)
    for term in search_terms:
        tokens = searchable_tokens(normalize_match_text(term.term))
        matching_indexes = indexes_for_term(index, tokens)
        for row_index in matching_indexes:
            terms_by_index[row_index].append(term)

    if not terms_by_index:
        fallback_terms = [
            term
            for term in search_terms
            if term.source in {"domain_fallback", "deterministic_it_fallback", "translated_title"}
        ] or list(search_terms[:3])
        for row_index in index.it_related_indexes:
            terms_by_index[row_index].extend(fallback_terms)
    return dict(terms_by_index)


def indexes_for_term(index: KldbSearchIndex, tokens: Sequence[str]) -> set[int]:
    if not tokens:
        return set()
    token_sets = [
        index.row_indexes_by_token[token]
        for token in tokens
        if token in index.row_indexes_by_token
    ]
    if not token_sets:
        return set()
    if len(token_sets) == 1:
        return set(token_sets[0])

    intersection = set(token_sets[0])
    for token_set in token_sets[1:]:
        intersection &= token_set
    if intersection:
        return intersection
    return set(min(token_sets, key=len))


def searchable_tokens(value: str) -> list[str]:
    stop_tokens = {"and", "und", "der", "die", "das", "in", "im", "fuer", "fur"}
    return [
        token
        for token in re.split(r"\s+", value)
        if len(token) >= 3 and token not in stop_tokens
    ]


def classify_match_confidence(
    role: CareerRole,
    selected_candidate: KldbCandidate | None,
) -> str:
    if selected_candidate is None:
        return "missing"
    if selected_candidate.score < 50.0:
        return "low_confidence"

    role_is_modern = is_modern_or_specialized_title(role.job_title)
    broad_match = is_broad_it_title(selected_candidate.title)
    if role_is_modern and broad_match and selected_candidate.original_title_similarity < 82.0:
        return "broad_it_category"

    if (
        selected_candidate.title_similarity >= 98.0
        and selected_candidate.term_source in {
            "original_title",
            "cleaned_title",
            "translated_title",
        }
    ):
        return "exact_title"

    if (
        selected_candidate.term_source in {
            "original_title",
            "cleaned_title",
            "translated_title",
        }
        and selected_candidate.title_similarity >= 84.0
    ):
        return "close_title"

    if selected_candidate.term_source == "esco_title":
        return "esco_based_fallback"

    if selected_candidate.term_source in {
        "domain_tags",
        "domain_fallback",
        "deterministic_it_fallback",
    }:
        if selected_candidate.original_title_similarity >= 78.0:
            return "close_title"
        return "domain_fallback"

    if selected_candidate.score >= 78.0:
        return "close_title"
    return "low_confidence"


def salary_band_and_score(
    salary_median_monthly_gross_eur: int | None,
    salary_value_capped: bool,
) -> tuple[str, int]:
    if salary_value_capped:
        return "capped", 5
    if salary_median_monthly_gross_eur is None:
        return "unknown", 0
    if salary_median_monthly_gross_eur < 4000:
        return "low", 1
    if salary_median_monthly_gross_eur < 5500:
        return "medium", 2
    if salary_median_monthly_gross_eur < 7000:
        return "high", 3
    return "very_high", 4


def kldb_level_from_code(kldb_code: str) -> str:
    normalized_code = normalize_kldb_code(kldb_code)
    if len(normalized_code) < 5 or not normalized_code[:5].isdigit():
        return ""
    return {
        "1": "Helfer",
        "2": "Fachkraft",
        "3": "Spezialist",
        "4": "Experte",
    }.get(normalized_code[4], "")


def kldb_lookup_attempts(kldb_code: str) -> list[KldbLookupAttempt]:
    normalized_code = normalize_kldb_code(kldb_code)
    if not normalized_code:
        return []
    level = kldb_level_from_code(normalized_code)
    attempts: list[KldbLookupAttempt] = []
    for code in dedupe_nonempty(
        [
            normalized_code,
            normalized_code[:4] if len(normalized_code) >= 5 else "",
            normalized_code[:3] if len(normalized_code) >= 4 else "",
        ]
    ):
        attempts.append(
            KldbLookupAttempt(
                code=code,
                level=level,
                broad_fallback=code != normalized_code,
            )
        )
    return attempts


def needs_review(
    salary_data: SalaryData | None,
    selected_candidate: KldbCandidate | None,
    candidates: Sequence[KldbCandidate],
    match_confidence: str,
    source_status: str,
    role: CareerRole,
) -> bool:
    if salary_data is None or salary_data.median_monthly_gross_eur is None:
        return True
    if selected_candidate is None:
        return True
    if match_confidence in NEEDS_REVIEW_CONFIDENCES:
        return True
    if len(candidates) > 1 and candidates[0].score - candidates[1].score <= 5.0:
        return True
    if salary_data.salary_value_capped:
        return True
    if salary_data.fallback_group_used:
        return True
    if salary_data.salary_fallback_to_ingesamt:
        return True
    if source_status in {
        "api_failed",
        "salary_group_not_found",
        "salary_missing",
        "salary_table_parse_failed",
    }:
        return True
    if is_modern_or_specialized_title(role.job_title) and is_broad_it_title(
        selected_candidate.title
    ):
        return True
    return False


