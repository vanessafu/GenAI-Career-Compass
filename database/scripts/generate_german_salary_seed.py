def flatten_payload(value: Any, prefix: str = "") -> Iterable[tuple[str, Any]]:
    if isinstance(value, dict):
        for key, child in value.items():
            child_prefix = f"{prefix}.{key}" if prefix else str(key)
            yield from flatten_payload(child, child_prefix)
    elif isinstance(value, list):
        for index, child in enumerate(value):
            child_prefix = f"{prefix}[{index}]"
            yield from flatten_payload(child, child_prefix)
    else:
        yield prefix, value


def looks_like_median_salary_key(key: str) -> bool:
    median_terms = ("median", "zentral", "p50", "mittler", "brutto", "entgelt")
    salary_terms = ("salary", "gehalt", "entgelt", "euro", "eur", "gross", "brutto")
    return any(term in key for term in median_terms) and any(
        term in key for term in salary_terms
    )


def parse_salary_value(value: Any) -> tuple[int | None, str, bool]:
    if value is None or isinstance(value, bool):
        return None, "", False
    if isinstance(value, (int, float)):
        number = int(round(float(value)))
        return number, format_int(number), False

    text = collapse_spaces(str(value))
    if not text:
        return None, "", False
    capped = text.startswith(">") or text.startswith("&gt;") or ">" in text[:3]
    match = re.search(r"\d[\d.,\s]*", text)
    if not match:
        return None, text, capped
    number = parse_localized_number_to_int(match.group(0))
    if number is None:
        return None, text, capped
    return number, text, capped


def parse_localized_number_to_int(value: str) -> int | None:
    number_text = re.sub(r"[^\d,.\s]", "", value)
    number_text = re.sub(r"\s+", "", number_text)
    if not number_text:
        return None

    has_comma = "," in number_text
    has_dot = "." in number_text
    normalized = number_text

    if has_comma and has_dot:
        if number_text.rfind(",") > number_text.rfind("."):
            normalized = number_text.replace(".", "").replace(",", ".")
        else:
            normalized = number_text.replace(",", "")
    elif has_comma:
        parts = number_text.split(",")
        if len(parts) == 2 and len(parts[1]) in {1, 2}:
            normalized = parts[0] + "." + parts[1]
        else:
            normalized = number_text.replace(",", "")
    elif has_dot:
        parts = number_text.split(".")
        if len(parts) == 2:
            before, after = parts
            if len(after) == 2 and len(before) >= 4:
                normalized = before + "." + after
            elif len(after) == 3 and len(before) <= 3:
                normalized = before + after
            elif len(after) in {1, 2}:
                normalized = before + "." + after
            else:
                normalized = before + after
        elif len(parts[-1]) == 2 and all(part.isdigit() for part in parts):
            normalized = "".join(parts[:-1]) + "." + parts[-1]
        else:
            normalized = number_text.replace(".", "")

    try:
        decimal_value = Decimal(normalized)
    except InvalidOperation:
        return None
    return int(decimal_value.quantize(Decimal("1"), rounding=ROUND_HALF_UP))


