#!/usr/bin/env python3
"""Generate a reviewable German salary seed CSV for Phase 7.

Phase 7 is local/offline data preparation only. It reads Career Compass roles
and existing ESCO mappings from Supabase, optionally matches them to a BA/KldB
occupation workbook, enriches those candidates from the official BA "Entgelte
nach Berufen im Vergleich" table when available, optionally tries a configured
Entgeltatlas API, and writes reviewable CSV artifacts. It never writes salary
data to Supabase.

Entgeltatlas values are occupational aggregate estimates, not exact salaries for
modern individual job titles such as MLOps Engineer or Cloud Security
Specialist. Every generated row includes a confidence label and a needs_review
flag so Phase 8 can import only an approved, reviewed seed file.

Examples:

    python scripts/generate_german_salary_seed.py --dry-run
    python scripts/generate_german_salary_seed.py
    python scripts/generate_german_salary_seed.py --limit 50
    python scripts/generate_german_salary_seed.py --role-id 123
    python scripts/generate_german_salary_seed.py --no-api
    python scripts/generate_german_salary_seed.py --kldb-xlsx data/raw/ba/berufs_und_taetigkeitsverzeichnis.xlsx
    python scripts/generate_german_salary_seed.py --fetch-salary-table --no-api

Required environment variables:
    SUPABASE_URL
    SUPABASE_SERVICE_ROLE_KEY

Optional Entgeltatlas API environment variables:
    ENTGELTATLAS_X_API_KEY
    ENTGELTATLAS_CLIENT_ID
    ENTGELTATLAS_CLIENT_SECRET
    ENTGELTATLAS_BASE_URL
"""

