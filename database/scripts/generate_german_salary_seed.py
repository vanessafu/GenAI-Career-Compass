class SalaryTableHtmlParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.rows: list[list[str]] = []
        self._current_row: list[str] | None = None
        self._current_cell: list[str] | None = None

    def handle_starttag(
        self,
        tag: str,
        attrs: Sequence[tuple[str, str | None]],
    ) -> None:
        if tag.casefold() == "tr":
            self._current_row = []
        elif tag.casefold() in {"th", "td"} and self._current_row is not None:
            self._current_cell = []

    def handle_data(self, data: str) -> None:
        if self._current_cell is not None:
            self._current_cell.append(data)

    def handle_endtag(self, tag: str) -> None:
        normalized_tag = tag.casefold()
        if normalized_tag in {"th", "td"} and self._current_cell is not None:
            if self._current_row is not None:
                self._current_row.append(collapse_spaces("".join(self._current_cell)))
            self._current_cell = None
        elif normalized_tag == "tr" and self._current_row is not None:
            if any(cell for cell in self._current_row):
                self.rows.append(self._current_row)
            self._current_row = None


def parse_salary_table_html(html: str) -> dict[str, SalaryTableRow]:
    parser = SalaryTableHtmlParser()
    parser.feed(html)
    rows = parse_salary_table_rows(parser.rows)
    if rows:
        return rows
    return parse_salary_table_plain_text(html)


def parse_salary_table_rows(raw_rows: Sequence[Sequence[str]]) -> dict[str, SalaryTableRow]:
    header_indexes: dict[str, int] = {}
    parsed_rows: dict[str, SalaryTableRow] = {}

    for raw_row in raw_rows:
        row = [collapse_spaces(cell) for cell in raw_row]
        if not any(row):
            continue

        detected = detect_salary_table_header(row)
        if detected:
            header_indexes = detected
            continue

        if not header_indexes:
            continue
        group_index = header_indexes.get("berufsgruppe")
        if group_index is None or group_index >= len(row):
            continue

        group_code, group_title = parse_salary_group(row[group_index])
        if not group_code:
            continue

        cells: dict[str, SalaryTableCell] = {}
        for key in SALARY_TABLE_COLUMNS:
            index = header_indexes.get(key)
            if index is None or index >= len(row):
                cells[key] = SalaryTableCell()
            else:
                cells[key] = parse_salary_table_cell(row[index])
        parsed_rows[group_code] = SalaryTableRow(
            group_code=group_code,
            group_title=group_title,
            cells=cells,
        )

    return parsed_rows


def detect_salary_table_header(row: Sequence[str]) -> dict[str, int]:
    indexes: dict[str, int] = {}
    for index, cell in enumerate(row):
        normalized = normalize_salary_table_header(cell)
        if "berufsgruppe" in normalized:
            indexes["berufsgruppe"] = index
        elif normalized == "insgesamt" or "insgesamt" in normalized:
            indexes["ingesamt"] = index
        elif "helfer" in normalized:
            indexes["helfer"] = index
        elif "fachkraft" in normalized or "fachkraefte" in normalized:
            indexes["fachkraefte"] = index
        elif "spezialist" in normalized:
            indexes["spezialisten"] = index
        elif "experte" in normalized:
            indexes["experten"] = index
    required = {"berufsgruppe", "ingesamt", "helfer", "fachkraefte", "spezialisten", "experten"}
    return indexes if required.issubset(indexes) else {}


def normalize_salary_table_header(value: str) -> str:
    normalized = unicodedata.normalize("NFKD", value)
    ascii_text = normalized.encode("ascii", "ignore").decode("ascii")
    ascii_text = ascii_text.casefold()
    ascii_text = ascii_text.replace("ae", "a").replace("ue", "u").replace("oe", "o")
    return re.sub(r"[^a-z0-9]+", "", ascii_text)


def parse_salary_group(value: str) -> tuple[str, str]:
    match = re.match(r"\s*(\d{3})\s*(.*)$", collapse_spaces(value))
    if not match:
        return "", ""
    group_code = match.group(1)
    group_title = match.group(2).strip(" -\u2013\u2014:\t")
    return group_code, group_title


def parse_salary_table_cell(value: str) -> SalaryTableCell:
    display = collapse_spaces(value)
    if not display or display.casefold() in {"x", "-", "\u2013", "\u2014"}:
        return SalaryTableCell(display=display, value=None, capped=False)
    capped = display.startswith(">") or display.startswith("&gt;") or ">" in display[:3]
    parsed_value, _, parsed_capped = parse_salary_value(display)
    return SalaryTableCell(
        display=display,
        value=parsed_value,
        capped=capped or parsed_capped,
    )


def parse_salary_table_plain_text(html: str) -> dict[str, SalaryTableRow]:
    text = re.sub(r"<[^>]+>", "\n", html)
    rows: dict[str, SalaryTableRow] = {}
    value_pattern = r"(?:&gt;|>)?\s*(?:\d[\d.,\s]*|x|-|\u2013)"
    row_pattern = re.compile(
        rf"(?P<group>\d{{3}}\s+[^\n\r]+?)\s+"
        rf"(?P<ingesamt>{value_pattern})\s+"
        rf"(?P<helfer>{value_pattern})\s+"
        rf"(?P<fachkraefte>{value_pattern})\s+"
        rf"(?P<spezialisten>{value_pattern})\s+"
        rf"(?P<experten>{value_pattern})(?:\s|$)",
        re.IGNORECASE,
    )
    for raw_line in text.splitlines():
        line = collapse_spaces(raw_line)
        if not line:
            continue
        match = row_pattern.search(line)
        if not match:
            continue
        group_code, group_title = parse_salary_group(match.group("group"))
        if not group_code:
            continue
        rows[group_code] = SalaryTableRow(
            group_code=group_code,
            group_title=group_title,
            cells={
                "ingesamt": parse_salary_table_cell(match.group("ingesamt")),
                "helfer": parse_salary_table_cell(match.group("helfer")),
                "fachkraefte": parse_salary_table_cell(match.group("fachkraefte")),
                "spezialisten": parse_salary_table_cell(match.group("spezialisten")),
                "experten": parse_salary_table_cell(match.group("experten")),
            },
        )
    return rows


def first_salary_for_key(
    flattened: Sequence[tuple[str, Any]],
    key_terms: Sequence[str],
) -> int | None:
    for key_path, value in flattened:
        key = key_path.casefold()
        if any(term in key for term in key_terms):
            parsed_value, _, _ = parse_salary_value(value)
            if parsed_value is not None:
                return parsed_value
    return None


def first_text_for_key(
    flattened: Sequence[tuple[str, Any]],
    key_terms: Sequence[str],
) -> str:
    for key_path, value in flattened:
        key = key_path.casefold()
        if any(term in key for term in key_terms) and isinstance(value, str):
            text = collapse_spaces(value)
            if text:
                return text
    return ""


