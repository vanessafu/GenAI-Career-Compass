def load_dotenv_file(path: Path) -> None:
    if not path.exists():
        return

    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        name, value = line.split("=", 1)
        name = name.strip()
        value = value.strip()
        if not name or name in os.environ:
            continue
        if (
            (value.startswith('"') and value.endswith('"'))
            or (value.startswith("'") and value.endswith("'"))
        ):
            value = value[1:-1]
        os.environ[name] = value


def get_required_supabase_env() -> tuple[str, str]:
    load_dotenv_file(Path(".env"))
    supabase_url = os.getenv("SUPABASE_URL", "").strip()
    service_role_key = os.getenv("SUPABASE_SERVICE_ROLE_KEY", "").strip()

    missing = []
    if not supabase_url:
        missing.append("SUPABASE_URL")
    if not service_role_key:
        missing.append("SUPABASE_SERVICE_ROLE_KEY")
    if missing:
        raise ValueError(
            "Missing required environment variable(s): " + ", ".join(missing)
        )
    if service_role_key.startswith("sb_publishable_"):
        raise ValueError(
            "SUPABASE_SERVICE_ROLE_KEY must be a secret key "
            "(sb_secret_...) or legacy service_role JWT, not a publishable key."
        )
    return supabase_url, service_role_key


def normalize_supabase_url(value: str) -> str:
    parsed = urllib.parse.urlparse(value.strip())
    if not parsed.scheme or not parsed.netloc:
        raise ValueError(
            "SUPABASE_URL must be a full URL, such as "
            "https://your-project-ref.supabase.co"
        )

    dashboard_prefix = "/dashboard/project/"
    if parsed.netloc == "supabase.com" and parsed.path.startswith(dashboard_prefix):
        project_ref = parsed.path[len(dashboard_prefix) :].split("/", 1)[0]
        if project_ref:
            return f"https://{project_ref}.supabase.co"
    return value.strip().rstrip("/")


def format_postgrest_in_filter(values: Iterable[Any]) -> str:
    formatted_values = []
    for value in values:
        text = str(value)
        if re.fullmatch(r"-?\d+", text):
            formatted_values.append(text)
        else:
            escaped = text.replace("\\", "\\\\").replace('"', '\\"')
            formatted_values.append(f'"{escaped}"')
    return "in.(" + ",".join(formatted_values) + ")"


def chunked(items: Sequence[Any], size: int = BATCH_SIZE) -> Iterable[Sequence[Any]]:
    for start in range(0, len(items), size):
        yield items[start : start + size]


class SupabaseRestClient:
    def __init__(
        self,
        supabase_url: str,
        service_role_key: str,
        schema: SchemaConfig = DEFAULT_SCHEMA,
        timeout_seconds: int = 30,
    ):
        self.rest_url = normalize_supabase_url(supabase_url) + "/rest/v1"
        self.service_role_key = service_role_key
        self.schema = schema
        self.timeout_seconds = timeout_seconds

    def validate_read_schema(self) -> None:
        checks = [
            (
                self.schema.roles_table,
                [
                    self.schema.role_id_column,
                    self.schema.job_title_column,
                    self.schema.domain_tags_column,
                ],
            ),
            (
                self.schema.mappings_table,
                [
                    self.schema.role_id_column,
                    self.schema.esco_title_column,
                    self.schema.esco_uri_column,
                ],
            ),
        ]
        for table, columns in checks:
            self._request(
                "GET",
                table,
                query=[("select", ",".join(columns)), ("limit", "1")],
            )

    def list_career_roles(
        self,
        role_id: str | None = None,
        limit: int | None = None,
    ) -> list[CareerRole]:
        extra_query = [("order", f"{self.schema.role_id_column}.asc")]
        if role_id is not None:
            extra_query.append((self.schema.role_id_column, f"eq.{role_id}"))
        rows = self._paged_get(
            self.schema.roles_table,
            select=",".join(
                [
                    self.schema.role_id_column,
                    self.schema.job_title_column,
                    self.schema.domain_tags_column,
                ]
            ),
            extra_query=extra_query,
            max_rows=limit,
        )
        role_ids = [
            str(row.get(self.schema.role_id_column))
            for row in rows
            if row.get(self.schema.role_id_column) is not None
        ]
        mappings_by_role_id = self.list_esco_mappings_by_role_id(role_ids)
        roles: list[CareerRole] = []
        for row in rows:
            role_id_value = str(row.get(self.schema.role_id_column))
            mapping = mappings_by_role_id.get(role_id_value, {})
            roles.append(
                CareerRole(
                    role_id=role_id_value,
                    job_title=str(row.get(self.schema.job_title_column) or ""),
                    domain_tags=str(row.get(self.schema.domain_tags_column) or ""),
                    esco_title=str(mapping.get(self.schema.esco_title_column) or ""),
                    esco_uri=str(mapping.get(self.schema.esco_uri_column) or ""),
                )
            )
        return roles

    def list_esco_mappings_by_role_id(
        self,
        role_ids: Sequence[str],
    ) -> dict[str, dict[str, Any]]:
        mappings: dict[str, dict[str, Any]] = {}
        if not role_ids:
            return mappings
        for role_id_chunk in chunked(list(role_ids), LOOKUP_FILTER_BATCH_SIZE):
            rows = self._request(
                "GET",
                self.schema.mappings_table,
                query=[
                    (
                        "select",
                        ",".join(
                            [
                                self.schema.role_id_column,
                                self.schema.esco_title_column,
                                self.schema.esco_uri_column,
                            ]
                        ),
                    ),
                    (
                        self.schema.role_id_column,
                        format_postgrest_in_filter(role_id_chunk),
                    ),
                    ("order", f"{self.schema.role_id_column}.asc"),
                ],
            ) or []
            for row in rows:
                key = str(row.get(self.schema.role_id_column))
                mappings.setdefault(key, row)
        return mappings

    def _paged_get(
        self,
        table: str,
        select: str,
        extra_query: Iterable[tuple[str, str]] | None = None,
        max_rows: int | None = None,
    ) -> list[dict[str, Any]]:
        rows: list[dict[str, Any]] = []
        start = 0
        while True:
            remaining = None if max_rows is None else max_rows - len(rows)
            if remaining is not None and remaining <= 0:
                break
            page_size = BATCH_SIZE if remaining is None else min(BATCH_SIZE, remaining)
            end = start + page_size - 1
            query = [("select", select)]
            if extra_query:
                query.extend(extra_query)
            page = self._request(
                "GET",
                table,
                query=query,
                extra_headers={
                    "Range-Unit": "items",
                    "Range": f"{start}-{end}",
                },
            )
            if not page:
                break
            rows.extend(page)
            if len(page) < page_size:
                break
            start += page_size
        return rows

    def _request(
        self,
        method: str,
        table: str,
        query: Iterable[tuple[str, str]] | None = None,
        payload: Any | None = None,
        prefer: str | None = None,
        extra_headers: dict[str, str] | None = None,
    ) -> Any:
        if method != "GET":
            raise SupabaseError("Phase 7 Supabase client is read-only and only allows GET.")

        encoded_table = urllib.parse.quote(table, safe="")
        url = f"{self.rest_url}/{encoded_table}"
        if query:
            url += "?" + urllib.parse.urlencode(list(query))

        body = None
        headers = self._auth_headers()
        if payload is not None:
            body = json.dumps(payload).encode("utf-8")
            headers["Content-Type"] = "application/json"
        if prefer:
            headers["Prefer"] = prefer
        if extra_headers:
            headers.update(extra_headers)

        request = urllib.request.Request(
            url,
            data=body,
            headers=headers,
            method=method,
        )
        try:
            with urllib.request.urlopen(
                request,
                timeout=self.timeout_seconds,
            ) as response:
                response_body = response.read().decode("utf-8")
        except urllib.error.HTTPError as error:
            error_body = error.read().decode("utf-8", errors="replace")
            raise SupabaseError(
                format_supabase_error(error.code, method, table, error_body)
            ) from error
        except urllib.error.URLError as error:
            raise SupabaseError(
                f"Could not reach Supabase REST API for table '{table}': {error.reason}"
            ) from error

        if not response_body:
            return None
        try:
            return json.loads(response_body)
        except json.JSONDecodeError as error:
            raise SupabaseError(
                f"Supabase returned non-JSON data for table '{table}'."
            ) from error

    def _auth_headers(self) -> dict[str, str]:
        headers = {
            "Accept": "application/json",
            "apikey": self.service_role_key,
            "User-Agent": "career-compass-german-salary-seed/1.0",
        }
        if not self.service_role_key.startswith(("sb_secret_", "sb_publishable_")):
            headers["Authorization"] = f"Bearer {self.service_role_key}"
        return headers


def format_supabase_error(
    status_code: int,
    method: str,
    table: str,
    response_body: str,
) -> str:
    try:
        error_json = json.loads(response_body)
    except json.JSONDecodeError:
        detail = response_body.strip()
    else:
        parts = [
            str(error_json.get("message") or "").strip(),
            str(error_json.get("details") or "").strip(),
            str(error_json.get("hint") or "").strip(),
        ]
        detail = " ".join(part for part in parts if part)
    if not detail:
        detail = "No response body returned."
    return (
        f"Supabase {method} failed for table '{table}' "
        f"with HTTP {status_code}: {detail}"
    )


def write_csv(path: Path, rows: Sequence[Mapping[str, str]], fieldnames: Sequence[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(fieldnames), extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow({field: row.get(field, "") for field in fieldnames})


def summarize_run(
    roles: Sequence[CareerRole],
    kldb_rows: Sequence[KldbOccupation],
    result: BuildResult,
    salary_lookup: (
        NoApiSalaryLookup
        | EntgeltatlasApiSalaryLookup
        | SalaryTableLookup
        | CombinedSalaryLookup
    ),
    output_path: Path,
    review_output_path: Path,
    dry_run: bool,
) -> RunStats:
    confidence_counts: collections.Counter[str] = collections.Counter(
        row["match_confidence"] for row in result.seed_rows
    )
    source_status_counts: collections.Counter[str] = collections.Counter(
        row["source_status"] for row in result.seed_rows
    )
    roles_with_candidate_matches = sum(1 for row in result.seed_rows if row["kldb_code"])
    roles_with_salary_values = sum(
        1 for row in result.seed_rows if row["salary_median_monthly_gross_eur"]
    )
    return RunStats(
        roles_loaded=len(roles),
        kldb_rows_loaded=len(kldb_rows),
        roles_with_kldb_candidate_matches=roles_with_candidate_matches,
        roles_with_salary_values_found=roles_with_salary_values,
        roles_missing_salary_values=len(result.seed_rows) - roles_with_salary_values,
        confidence_counts=confidence_counts,
        needs_review_count=sum(1 for row in result.seed_rows if row["needs_review"] == "true"),
        source_status_counts=source_status_counts,
        output_path=output_path,
        review_output_path=review_output_path,
        api_configured=salary_lookup.api_configured,
        api_requests_made=salary_lookup.request_count,
        dry_run=dry_run,
    )


def print_summary(stats: RunStats) -> None:
    print(f"Roles loaded: {stats.roles_loaded}")
    print(f"KldB rows loaded: {stats.kldb_rows_loaded}")
    print(
        "Roles with KldB candidate matches: "
        f"{stats.roles_with_kldb_candidate_matches}"
    )
    print(f"Roles with salary values found: {stats.roles_with_salary_values_found}")
    print(f"Roles missing salary values: {stats.roles_missing_salary_values}")
    print("Count by match_confidence:")
    if stats.confidence_counts:
        for confidence, count in sorted(stats.confidence_counts.items()):
            print(f"  {confidence}: {count}")
    else:
        print("  (none)")
    print("Count by source_status:")
    if stats.source_status_counts:
        for status, count in sorted(stats.source_status_counts.items()):
            print(f"  {status}: {count}")
    else:
        print("  (none)")
    print(f"Count needing review: {stats.needs_review_count}")
    print(f"Output CSV path: {stats.output_path}")
    print(f"Review CSV path: {stats.review_output_path}")
    print(f"Entgeltatlas API configured: {'yes' if stats.api_configured else 'no'}")
    print(f"Entgeltatlas API requests made: {stats.api_requests_made}")
    print(f"Dry run: {'yes' if stats.dry_run else 'no'}")
    print("No Supabase writes were made; Phase 7 only writes local CSV artifacts.")


