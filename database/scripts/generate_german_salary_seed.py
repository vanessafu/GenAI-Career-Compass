def build_salary_table_lookup(
    salary_table_html: Path | None,
    salary_table_url: str | None,
    fetch_salary_table: bool,
) -> SalaryTableLookup:
    explicit_html_path = salary_table_html
    url = collapse_spaces(salary_table_url or "")

    if explicit_html_path is not None and explicit_html_path.exists():
        return parse_salary_table_file(explicit_html_path)

    if fetch_salary_table or url:
        cache_path = explicit_html_path or DEFAULT_SALARY_TABLE_HTML
        fetch_url = url or DEFAULT_SALARY_TABLE_URL
        html, error = fetch_salary_table_html(fetch_url, cache_path)
        if error:
            return SalaryTableLookup(
                table_rows=None,
                source_label=fetch_url,
                parse_error=error,
            )
        return parse_salary_table_content(html, f"{fetch_url} cached at {cache_path}")

    if explicit_html_path is not None:
        return SalaryTableLookup(
            table_rows=None,
            source_label=str(explicit_html_path),
            parse_error=f"BA salary table HTML not found: {explicit_html_path}",
        )

    if DEFAULT_SALARY_TABLE_HTML.exists():
        return parse_salary_table_file(DEFAULT_SALARY_TABLE_HTML)

    return SalaryTableLookup()


def parse_salary_table_file(path: Path) -> SalaryTableLookup:
    try:
        html = path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        try:
            html = path.read_text(encoding="latin-1")
        except OSError as error:
            return SalaryTableLookup(
                table_rows=None,
                source_label=str(path),
                parse_error=f"Could not read BA salary table HTML: {error}",
            )
    except OSError as error:
        return SalaryTableLookup(
            table_rows=None,
            source_label=str(path),
            parse_error=f"Could not read BA salary table HTML: {error}",
        )
    return parse_salary_table_content(html, str(path))


def parse_salary_table_content(html: str, source_label: str) -> SalaryTableLookup:
    try:
        table_rows = parse_salary_table_html(html)
    except Exception as error:
        return SalaryTableLookup(
            table_rows=None,
            source_label=source_label,
            parse_error=f"BA salary table parse failed for {source_label}: {error}",
        )
    if not table_rows:
        return SalaryTableLookup(
            table_rows=None,
            source_label=source_label,
            parse_error=(
                f"BA salary table parse failed for {source_label}: "
                "no Berufsgruppe rows were found."
            ),
        )
    return SalaryTableLookup(table_rows=table_rows, source_label=source_label)


def fetch_salary_table_html(url: str, cache_path: Path) -> tuple[str, str]:
    request = urllib.request.Request(
        url,
        headers={
            "Accept": "text/html,application/xhtml+xml",
            "User-Agent": "career-compass-german-salary-seed/1.0",
        },
        method="GET",
    )
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            charset = response.headers.get_content_charset() or "utf-8"
            html = response.read().decode(charset, errors="replace")
    except urllib.error.HTTPError as error:
        return "", f"BA salary table fetch failed with HTTP {error.code} for {url}."
    except urllib.error.URLError as error:
        return "", f"BA salary table fetch failed for {url}: {error.reason}"
    except OSError as error:
        return "", f"BA salary table fetch failed for {url}: {error}"

    try:
        cache_path.parent.mkdir(parents=True, exist_ok=True)
        cache_path.write_text(html, encoding="utf-8")
    except OSError as error:
        return html, f"BA salary table fetched but could not be cached at {cache_path}: {error}"
    return html, ""


def read_dotenv_values(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}

    values: dict[str, str] = {}
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        name, value = line.split("=", 1)
        name = name.strip()
        value = value.strip()
        if not name:
            continue
        if (
            (value.startswith('"') and value.endswith('"'))
            or (value.startswith("'") and value.endswith("'"))
        ):
            value = value[1:-1]
        values[name] = value
    return values


def load_kldb_workbook(path: Path) -> list[KldbOccupation]:
    if not path.exists():
        raise FileNotFoundError(f"KldB workbook not found: {path}")
    if path.suffix.casefold() == ".csv":
        rows = read_delimited_rows(path)
    elif path.suffix.casefold() == ".xlsx":
        rows = read_xlsx_rows(path)
    else:
        raise KldbWorkbookError(
            f"Unsupported KldB workbook format '{path.suffix}'. Use .xlsx or .csv."
        )

    if not rows:
        return []

    header_index, title_index, code_index = detect_kldb_columns(rows)
    occupations: list[KldbOccupation] = []
    seen: set[tuple[str, str]] = set()
    for source_row_number, row in enumerate(rows[header_index + 1 :], start=header_index + 2):
        title = collapse_spaces(cell_at(row, title_index))
        kldb_code = normalize_kldb_code(cell_at(row, code_index))
        if not title or not kldb_code:
            continue
        key = (normalize_match_text(title), kldb_code)
        if key in seen:
            continue
        seen.add(key)
        occupations.append(
            KldbOccupation(
                title=title,
                kldb_code=kldb_code,
                source_row_number=source_row_number,
            )
        )
    return occupations


def read_delimited_rows(path: Path) -> list[list[str]]:
    with path.open(newline="", encoding="utf-8-sig") as handle:
        sample = handle.read(4096)
        handle.seek(0)
        dialect = csv.Sniffer().sniff(sample, delimiters=",;\t")
        return [list(row) for row in csv.reader(handle, dialect)]


def read_xlsx_rows(path: Path) -> list[list[str]]:
    try:
        with zipfile.ZipFile(path) as archive:
            shared_strings = read_shared_strings(archive)
            sheet_names = worksheet_names_in_order(archive)
            if not sheet_names:
                raise KldbWorkbookError("No worksheet XML files found in KldB workbook.")
            parsed_sheets = [
                parse_xlsx_sheet_rows(archive.read(sheet_name), shared_strings, path)
                for sheet_name in sheet_names
            ]
    except zipfile.BadZipFile as error:
        raise KldbWorkbookError(f"Could not read .xlsx workbook '{path}'.") from error
    except KeyError as error:
        raise KldbWorkbookError(
            f"KldB workbook '{path}' is missing an expected XLSX part: {error}."
        ) from error

    for rows in parsed_sheets:
        try:
            detect_kldb_columns(rows)
        except KldbWorkbookError:
            continue
        return rows
    for rows in parsed_sheets:
        if rows:
            return rows
    return []


def parse_xlsx_sheet_rows(
    sheet_xml: bytes,
    shared_strings: Sequence[str],
    path: Path,
) -> list[list[str]]:
    try:
        root = ElementTree.fromstring(sheet_xml)
    except ElementTree.ParseError as error:
        raise KldbWorkbookError(f"Could not parse worksheet XML in '{path}'.") from error

    rows: list[list[str]] = []
    for row_element in root.findall(".//{*}sheetData/{*}row"):
        values_by_column: dict[int, str] = {}
        next_column_index = 0
        for cell in row_element.findall("{*}c"):
            cell_ref = cell.attrib.get("r", "")
            column_index = column_index_from_cell_ref(cell_ref)
            if column_index is None:
                column_index = next_column_index
            values_by_column[column_index] = xlsx_cell_value(cell, shared_strings)
            next_column_index = max(next_column_index, column_index + 1)
        if values_by_column:
            max_column = max(values_by_column)
            rows.append([values_by_column.get(index, "") for index in range(max_column + 1)])
    return rows


def read_shared_strings(archive: zipfile.ZipFile) -> list[str]:
    try:
        raw_xml = archive.read("xl/sharedStrings.xml")
    except KeyError:
        return []
    try:
        root = ElementTree.fromstring(raw_xml)
    except ElementTree.ParseError:
        return []
    values: list[str] = []
    for item in root.findall("{*}si"):
        text_parts = [node.text or "" for node in item.findall(".//{*}t")]
        values.append("".join(text_parts))
    return values


def worksheet_names_in_order(archive: zipfile.ZipFile) -> list[str]:
    fallback_names = sorted(
        name
        for name in archive.namelist()
        if name.startswith("xl/worksheets/") and name.endswith(".xml")
    )
    try:
        workbook_root = ElementTree.fromstring(archive.read("xl/workbook.xml"))
        relationships_root = ElementTree.fromstring(
            archive.read("xl/_rels/workbook.xml.rels")
        )
    except (KeyError, ElementTree.ParseError):
        return fallback_names

    targets_by_id = {
        relationship.attrib.get("Id", ""): relationship.attrib.get("Target", "")
        for relationship in relationships_root
    }
    ordered_names: list[str] = []
    for sheet in workbook_root.findall(".//{*}sheet"):
        relationship_id = sheet.attrib.get(
            "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id",
            "",
        )
        target = targets_by_id.get(relationship_id, "")
        if not target:
            continue
        normalized_target = target.lstrip("/")
        if not normalized_target.startswith("xl/"):
            normalized_target = "xl/" + normalized_target
        if normalized_target in fallback_names:
            ordered_names.append(normalized_target)
    return ordered_names or fallback_names


def column_index_from_cell_ref(cell_ref: str) -> int | None:
    match = re.match(r"([A-Z]+)", cell_ref or "")
    if not match:
        return None
    index = 0
    for char in match.group(1):
        index = index * 26 + (ord(char) - ord("A") + 1)
    return index - 1


def xlsx_cell_value(cell: ElementTree.Element, shared_strings: Sequence[str]) -> str:
    cell_type = cell.attrib.get("t", "")
    if cell_type == "inlineStr":
        return collapse_spaces("".join(node.text or "" for node in cell.findall(".//{*}t")))
    value_element = cell.find("{*}v")
    if value_element is None or value_element.text is None:
        return ""
    raw_value = value_element.text
    if cell_type == "s":
        try:
            return shared_strings[int(raw_value)]
        except (ValueError, IndexError):
            return ""
    return collapse_spaces(raw_value)


def detect_kldb_columns(rows: Sequence[Sequence[str]]) -> tuple[int, int, int]:
    best: tuple[int, int, int, int] | None = None
    for header_index, row in enumerate(rows[:20]):
        title_index = detect_title_column(row)
        code_index = detect_code_column(row)
        if title_index is None or code_index is None:
            continue
        score = header_row_score(row, title_index, code_index)
        if best is None or score > best[0]:
            best = (score, header_index, title_index, code_index)
    if best is None:
        raise KldbWorkbookError(
            "Could not detect KldB title/code columns. Expected headers such as "
            "Berufsbenennung, Bezeichnung, Beruf, Titel, KldB, KldB-Schluessel, "
            "Systematiknummer, or Code."
        )
    _, header_index, title_index, code_index = best
    return header_index, title_index, code_index


def detect_title_column(row: Sequence[str]) -> int | None:
    best_score = 0
    best_index: int | None = None
    for index, header in enumerate(row):
        normalized = normalize_header(header)
        score = 0
        if normalized in {"berufsbenennung", "berufsbezeichnung", "bezeichnung", "beruf", "titel"}:
            score = 100
        elif "berufsbenennung" in normalized or "berufsbezeichnung" in normalized:
            score = 95
        elif "bezeichnung" in normalized or "beruf" in normalized or "titel" in normalized:
            score = 75
        if "kldb" in normalized or "schluessel" in normalized or "systematik" in normalized:
            score -= 50
        if score > best_score:
            best_score = score
            best_index = index
    return best_index if best_score >= 60 else None


def detect_code_column(row: Sequence[str]) -> int | None:
    best_score = 0
    best_index: int | None = None
    for index, header in enumerate(row):
        normalized = normalize_header(header)
        score = 0
        if normalized in {"kldb", "kldb2010", "kldbschluessel", "systematiknummer", "code"}:
            score = 100
        elif "kldb" in normalized:
            score = 95
        elif "schluessel" in normalized or "schlussel" in normalized:
            score = 90
        elif "systematik" in normalized:
            score = 85
        elif normalized.endswith("code") or normalized == "code":
            score = 65
        if score > best_score:
            best_score = score
            best_index = index
    return best_index if best_score >= 60 else None


def normalize_header(value: str) -> str:
    text = normalize_match_text(value)
    return re.sub(r"[^a-z0-9]+", "", text)


def header_row_score(row: Sequence[str], title_index: int, code_index: int) -> int:
    title_header = normalize_header(cell_at(row, title_index))
    code_header = normalize_header(cell_at(row, code_index))
    return len(title_header) + len(code_header) + 100


def cell_at(row: Sequence[str], index: int) -> str:
    if index < 0 or index >= len(row):
        return ""
    return str(row[index] or "")


def normalize_kldb_code(value: str) -> str:
    text = collapse_spaces(value)
    if re.fullmatch(r"\d+\.0+", text):
        text = text.split(".", 1)[0]
    text = re.sub(r"\s+", "", text)
    return text


def load_manual_overrides(path: Path) -> list[ManualSalaryOverride]:
    if not path.exists():
        return []
    with path.open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames is None:
            return []
        overrides: list[ManualSalaryOverride] = []
        for row in reader:
            role_id = collapse_spaces(row.get("role_id") or "")
            job_title = collapse_spaces(row.get("job_title") or "")
            if not role_id and not job_title:
                continue
            salary_median = parse_optional_int(row.get("salary_median_monthly_gross_eur"))
            salary_capped = parse_bool(row.get("salary_value_capped"))
            salary_band = collapse_spaces(row.get("salary_band") or "")
            salary_score = parse_optional_int(row.get("salary_score"))
            if not salary_band or salary_score is None:
                salary_band, computed_score = salary_band_and_score(salary_median, salary_capped)
                salary_score = computed_score
            match_confidence = collapse_spaces(row.get("match_confidence") or "exact_title")
            if match_confidence not in VALID_CONFIDENCES:
                match_confidence = "low_confidence"
            overrides.append(
                ManualSalaryOverride(
                    role_id=role_id,
                    job_title=job_title,
                    kldb_code=collapse_spaces(row.get("kldb_code") or ""),
                    entgeltatlas_match_title=collapse_spaces(
                        row.get("entgeltatlas_match_title") or ""
                    ),
                    salary_median_monthly_gross_eur=salary_median,
                    salary_median_display=collapse_spaces(
                        row.get("salary_median_display") or ""
                    ),
                    salary_low_monthly_gross_eur=parse_optional_int(
                        row.get("salary_low_monthly_gross_eur")
                    ),
                    salary_high_monthly_gross_eur=parse_optional_int(
                        row.get("salary_high_monthly_gross_eur")
                    ),
                    salary_value_capped=salary_capped,
                    salary_band=salary_band,
                    salary_score=salary_score,
                    match_confidence=match_confidence,
                    notes=collapse_spaces(row.get("notes") or ""),
                )
            )
    return overrides


def parse_optional_int(value: Any) -> int | None:
    if value is None:
        return None
    text = collapse_spaces(str(value))
    if not text:
        return None
    parsed_value, _, _ = parse_salary_value(text)
    return parsed_value


def parse_bool(value: Any) -> bool:
    return collapse_spaces(str(value or "")).casefold() in {"1", "true", "yes", "y", "ja"}


def manual_override_indexes(
    overrides: Sequence[ManualSalaryOverride],
) -> tuple[dict[str, ManualSalaryOverride], dict[str, ManualSalaryOverride]]:
    by_role_id: dict[str, ManualSalaryOverride] = {}
    by_job_title: dict[str, ManualSalaryOverride] = {}
    for override in overrides:
        if override.role_id:
            by_role_id[override.role_id] = override
        elif override.job_title:
            by_job_title[override.job_title] = override
    return by_role_id, by_job_title


def find_manual_override(
    role: CareerRole,
    by_role_id: Mapping[str, ManualSalaryOverride],
    by_job_title: Mapping[str, ManualSalaryOverride],
) -> ManualSalaryOverride | None:
    if role.role_id in by_role_id:
        return by_role_id[role.role_id]
    return by_job_title.get(role.job_title)


def build_salary_seed_rows(
    roles: Sequence[CareerRole],
    kldb_rows: Sequence[KldbOccupation],
    salary_lookup: (
        NoApiSalaryLookup
        | EntgeltatlasApiSalaryLookup
        | SalaryTableLookup
        | CombinedSalaryLookup
    ),
    manual_overrides: Sequence[ManualSalaryOverride],
    top_k: int = DEFAULT_TOP_K,
) -> BuildResult:
    override_by_role_id, override_by_job_title = manual_override_indexes(manual_overrides)
    kldb_index = build_kldb_search_index(kldb_rows)
    seed_rows: list[dict[str, str]] = []
    review_rows: list[dict[str, str]] = []

    for role in roles:
        terms = generate_search_terms(role)
        candidates = match_kldb_candidates(role, kldb_index, terms, top_k=top_k)
        override = find_manual_override(role, override_by_role_id, override_by_job_title)
        if override is not None:
            seed_row, review_row = build_manual_override_rows(
                role,
                terms,
                candidates,
                override,
            )
            seed_rows.append(seed_row)
            review_rows.append(review_row)
            continue

        selected_candidate, salary_result = select_salary_candidate(candidates, salary_lookup)
        salary_data = salary_result.data
        match_confidence = classify_match_confidence(role, selected_candidate)
        if selected_candidate is None:
            source_status = salary_lookup.default_status
        else:
            source_status = salary_result.source_status
        source_status = normalize_source_status(source_status, salary_data)
        review = needs_review(
            salary_data=salary_data,
            selected_candidate=selected_candidate,
            candidates=candidates,
            match_confidence=match_confidence,
            source_status=source_status,
            role=role,
        )
        band, score = salary_band_and_score(
            None if salary_data is None else salary_data.median_monthly_gross_eur,
            False if salary_data is None else salary_data.salary_value_capped,
        )
        notes = build_notes(role, candidates, selected_candidate, salary_result, kldb_rows)
        seed_rows.append(
            seed_row_from_values(
                role=role,
                entgeltatlas_query="" if selected_candidate is None else selected_candidate.matched_term,
                entgeltatlas_match_title=match_title_from_selection(selected_candidate, salary_data),
                kldb_code="" if selected_candidate is None else selected_candidate.kldb_code,
                entgeltatlas_url="" if salary_data is None else salary_data.entgeltatlas_url,
                salary_data=salary_data,
                salary_band=band,
                salary_score=score,
                match_confidence=match_confidence,
                source=source_label(selected_candidate, salary_data),
                source_status=source_status,
                needs_review_flag=review,
                notes=notes,
            )
        )
        review_rows.append(
            review_row_from_values(
                role=role,
                search_terms=terms,
                candidates=candidates,
                selected_candidate=selected_candidate,
                selected_salary=salary_data,
                salary_band=band,
                salary_score=score,
                match_confidence=match_confidence,
                needs_review_flag=review,
                source_status=source_status,
                notes=notes,
            )
        )

    return BuildResult(seed_rows=seed_rows, review_rows=review_rows)


def select_salary_candidate(
    candidates: Sequence[KldbCandidate],
    salary_lookup: (
        NoApiSalaryLookup
        | EntgeltatlasApiSalaryLookup
        | SalaryTableLookup
        | CombinedSalaryLookup
    ),
) -> tuple[KldbCandidate | None, SalaryLookupResult]:
    if not candidates:
        return None, SalaryLookupResult(
            data=None,
            source_status=salary_lookup.default_status,
            notes="No KldB candidate available for salary lookup.",
        )

    selected_candidate = candidates[0]
    result = salary_lookup.lookup(selected_candidate)
    return selected_candidate, result


def match_title_from_selection(
    selected_candidate: KldbCandidate | None,
    salary_data: SalaryData | None,
) -> str:
    if salary_data is not None and salary_data.match_title:
        return salary_data.match_title
    if selected_candidate is not None:
        return selected_candidate.title
    return ""


def normalize_source_status(
    source_status: str,
    salary_data: SalaryData | None,
) -> str:
    if salary_data is None:
        return source_status
    if source_status in {
        "salary_table_success",
        "salary_group_not_found",
        "salary_missing",
        "salary_table_parse_failed",
        "no_salary_table_configured",
    }:
        return source_status
    return salary_source_status_for_data(salary_data)


def source_label(
    selected_candidate: KldbCandidate | None,
    salary_data: SalaryData | None,
) -> str:
    if salary_data is not None:
        if salary_data.salary_group_code:
            return "ba_salary_table"
        return "entgeltatlas_api"
    if selected_candidate is not None:
        return "kldb_candidate"
    return "no_kldb_match"


def build_notes(
    role: CareerRole,
    candidates: Sequence[KldbCandidate],
    selected_candidate: KldbCandidate | None,
    salary_result: SalaryLookupResult,
    kldb_rows: Sequence[KldbOccupation],
) -> str:
    notes: list[str] = []
    if not kldb_rows:
        notes.append("No KldB workbook provided; KldB fields require review.")
    if selected_candidate is None:
        notes.append("No usable KldB candidate found.")
    else:
        notes.append(selected_candidate.reason)
    if salary_result.notes:
        notes.append(salary_result.notes)
    if salary_result.data is None or salary_result.data.median_monthly_gross_eur is None:
        notes.append("No salary value found; Phase 8 import should wait for review.")
    if salary_result.data is not None and salary_result.data.lookup_code_used:
        notes.append(
            "Salary lookup used KldB code "
            f"{salary_result.data.lookup_code_used}"
            + (
                f" ({salary_result.data.lookup_level_used})."
                if salary_result.data.lookup_level_used
                else "."
            )
        )
    if salary_result.data is not None and salary_result.data.fallback_group_used:
        notes.append("Broader KldB fallback code used; needs review.")
    if salary_result.data is not None and salary_result.data.salary_fallback_to_ingesamt:
        notes.append("Salary table fell back to Insgesamt; needs review.")
    if is_modern_or_specialized_title(role.job_title):
        notes.append("Modern/specialized role title; broad occupation aggregate needs review.")
    if len(candidates) > 1 and candidates[0].score - candidates[1].score <= 5.0:
        notes.append("Top KldB candidates have similar scores.")
    return " ".join(dedupe_nonempty(notes))


