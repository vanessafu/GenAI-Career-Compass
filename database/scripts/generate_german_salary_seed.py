class SalaryTableLookup:
    api_configured = False
    request_count = 0

    def __init__(
        self,
        table_rows: Mapping[str, SalaryTableRow] | None = None,
        source_label: str = "",
        parse_error: str = "",
    ):
        self.table_rows = dict(table_rows) if table_rows is not None else None
        self.source_label = source_label
        self.parse_error = parse_error
        if parse_error:
            self.default_status = "salary_table_parse_failed"
        elif self.table_rows is None:
            self.default_status = "no_salary_table_configured"
        else:
            self.default_status = "salary_missing"

    @property
    def configured(self) -> bool:
        return self.table_rows is not None or bool(self.parse_error)

    def lookup(self, candidate: KldbCandidate) -> SalaryLookupResult:
        if self.parse_error:
            return SalaryLookupResult(
                data=None,
                source_status="salary_table_parse_failed",
                notes=self.parse_error,
            )
        if self.table_rows is None:
            return SalaryLookupResult(
                data=None,
                source_status="no_salary_table_configured",
                notes="No BA salary table HTML or URL configured.",
            )

        kldb_code = normalize_kldb_code(candidate.kldb_code)
        group_code = kldb_code[:3] if len(kldb_code) >= 3 else ""
        if not group_code:
            return SalaryLookupResult(
                data=None,
                source_status="salary_group_not_found",
                notes="Selected KldB candidate has no 3-digit salary group code.",
            )

        salary_row = self.table_rows.get(group_code)
        if salary_row is None:
            return SalaryLookupResult(
                data=salary_data_from_table_row(
                    candidate=candidate,
                    salary_row=None,
                    group_code=group_code,
                    selected_column="",
                    selected_cell=SalaryTableCell(),
                    fallback_to_ingesamt=False,
                ),
                source_status="salary_group_not_found",
                notes=f"No BA salary table row found for Berufsgruppe {group_code}.",
            )

        level = kldb_level_from_code(kldb_code)
        preferred_key = SALARY_TABLE_LEVEL_COLUMNS.get(level, "")
        selected_key = preferred_key or "ingesamt"
        selected_column = SALARY_TABLE_COLUMNS.get(selected_key, "Insgesamt")
        selected_cell = salary_row.cells.get(selected_key, SalaryTableCell())
        fallback_to_ingesamt = False
        notes: list[str] = []

        if selected_cell.value is None and selected_key != "ingesamt":
            selected_key = "ingesamt"
            selected_column = "Insgesamt"
            selected_cell = salary_row.cells.get("ingesamt", SalaryTableCell())
            fallback_to_ingesamt = True
            notes.append(
                f"{SALARY_TABLE_COLUMNS.get(preferred_key, level or 'level')} value "
                f"missing for Berufsgruppe {group_code}; used Insgesamt."
            )

        salary_data = salary_data_from_table_row(
            candidate=candidate,
            salary_row=salary_row,
            group_code=group_code,
            selected_column=selected_column,
            selected_cell=selected_cell,
            fallback_to_ingesamt=fallback_to_ingesamt,
        )

        if selected_cell.value is None:
            notes.append(f"BA salary table has no usable salary value for Berufsgruppe {group_code}.")
            return SalaryLookupResult(
                data=salary_data,
                source_status="salary_missing",
                notes=" ".join(notes),
            )

        notes.append(
            f"Salary parsed from BA salary table group {group_code} "
            f"({salary_row.group_title}), column {selected_column}."
        )
        if selected_cell.capped:
            notes.append("BA salary table returned a capped display value.")
        return SalaryLookupResult(
            data=salary_data,
            source_status="salary_table_success",
            notes=" ".join(dedupe_nonempty(notes)),
        )


def salary_data_from_table_row(
    candidate: KldbCandidate,
    salary_row: SalaryTableRow | None,
    group_code: str,
    selected_column: str,
    selected_cell: SalaryTableCell,
    fallback_to_ingesamt: bool,
) -> SalaryData:
    cells = {} if salary_row is None else salary_row.cells
    kldb_code = normalize_kldb_code(candidate.kldb_code)
    return SalaryData(
        median_monthly_gross_eur=selected_cell.value,
        median_display=selected_cell.display if selected_cell.value is not None else "",
        salary_value_capped=selected_cell.capped,
        match_title=candidate.title,
        region="Deutschland",
        data_period="BA Entgelte nach Berufen im Vergleich",
        lookup_code_used=kldb_code,
        lookup_level_used=kldb_level_from_code(kldb_code),
        salary_group_code=group_code,
        salary_source_group_title="" if salary_row is None else salary_row.group_title,
        salary_selected_column=selected_column,
        salary_ingesamt_monthly_gross_eur=salary_table_value(cells, "ingesamt"),
        salary_helfer_monthly_gross_eur=salary_table_value(cells, "helfer"),
        salary_fachkraefte_monthly_gross_eur=salary_table_value(cells, "fachkraefte"),
        salary_spezialisten_monthly_gross_eur=salary_table_value(cells, "spezialisten"),
        salary_experten_monthly_gross_eur=salary_table_value(cells, "experten"),
        salary_fallback_to_ingesamt=fallback_to_ingesamt,
    )


def salary_table_value(
    cells: Mapping[str, SalaryTableCell],
    key: str,
) -> int | None:
    cell = cells.get(key)
    return None if cell is None else cell.value


class CombinedSalaryLookup:
    def __init__(
        self,
        api_lookup: NoApiSalaryLookup | EntgeltatlasApiSalaryLookup,
        table_lookup: SalaryTableLookup,
    ):
        self.api_lookup = api_lookup
        self.table_lookup = table_lookup

    @property
    def default_status(self) -> str:
        if self.table_lookup.configured:
            return self.table_lookup.default_status
        return self.api_lookup.default_status

    @property
    def api_configured(self) -> bool:
        return self.api_lookup.api_configured

    @property
    def request_count(self) -> int:
        return self.api_lookup.request_count + self.table_lookup.request_count

    def lookup(self, candidate: KldbCandidate) -> SalaryLookupResult:
        api_result: SalaryLookupResult | None = None
        if self.api_lookup.api_configured:
            api_result = self.api_lookup.lookup(candidate)
            if api_result.data is not None and api_result.data.median_monthly_gross_eur is not None:
                return api_result

        table_result = self.table_lookup.lookup(candidate)
        if table_result.source_status != "no_salary_table_configured":
            if api_result is not None and api_result.notes:
                table_result = SalaryLookupResult(
                    data=table_result.data,
                    source_status=table_result.source_status,
                    notes=" ".join(dedupe_nonempty([api_result.notes, table_result.notes])),
                )
            return table_result

        if api_result is not None:
            return api_result
        return self.api_lookup.lookup(candidate)


class EntgeltatlasApiSalaryLookup:
    default_status = "api_missing"
    api_configured = True

    def __init__(
        self,
        base_url: str,
        x_api_key: str,
        client_id: str,
        client_secret: str,
        cache_dir: Path,
        timeout_seconds: int = 30,
        min_request_interval_seconds: float = 0.35,
    ):
        self.base_url = base_url.rstrip("/")
        self.x_api_key = x_api_key
        self.client_id = client_id
        self.client_secret = client_secret
        self.cache_dir = cache_dir
        self.timeout_seconds = timeout_seconds
        self.min_request_interval_seconds = min_request_interval_seconds
        self._last_request_at = 0.0
        self._memory_cache: dict[str, SalaryLookupResult] = {}
        self.request_count = 0

    def lookup(self, candidate: KldbCandidate) -> SalaryLookupResult:
        cache_key = candidate.kldb_code or normalize_match_text(candidate.title)
        if cache_key in self._memory_cache:
            return self._memory_cache[cache_key]

        saw_failure = False
        saw_missing = False
        notes: list[str] = []
        for attempt in kldb_lookup_attempts(candidate.kldb_code):
            for url in self._candidate_urls(attempt):
                response = self._load_or_request(url)
                status_code = int(response.get("status_code") or 0)
                if 200 <= status_code < 300:
                    parsed = self._parse_successful_response(
                        response,
                        fallback_title=candidate.title,
                        attempt=attempt,
                    )
                    if parsed.data is not None:
                        self._memory_cache[cache_key] = parsed
                        return parsed
                    saw_missing = True
                    notes.append(parsed.notes)
                elif status_code == 404:
                    saw_missing = True
                else:
                    saw_failure = True
                    notes.append(
                        f"API returned HTTP {status_code} for lookup code {attempt.code}."
                    )

        if saw_failure:
            result = SalaryLookupResult(
                data=None,
                source_status="api_failed",
                notes=" ".join(dedupe_nonempty(notes)) or "Entgeltatlas API lookup failed.",
            )
        elif saw_missing:
            result = SalaryLookupResult(
                data=None,
                source_status="api_missing",
                notes="Entgeltatlas API returned no salary value for candidate.",
            )
        else:
            result = SalaryLookupResult(
                data=None,
                source_status="api_failed",
                notes="Entgeltatlas API lookup produced no usable response.",
            )
        self._memory_cache[cache_key] = result
        return result

    def _candidate_urls(self, attempt: KldbLookupAttempt) -> list[str]:
        params = {
            "region": "Deutschland",
            "gender": "Gesamt",
            "age": "Gesamt",
            "industry": "Gesamt",
        }
        if attempt.level:
            params["anforderungsniveau"] = attempt.level
        query = urllib.parse.urlencode(params)
        code = urllib.parse.quote(attempt.code)
        if "{code}" in self.base_url:
            formatted_url = self.base_url.format(code=code)
            separator = "&" if "?" in formatted_url else "?"
            return [formatted_url + separator + query]

        if self.base_url.endswith("/entgelte"):
            return [f"{self.base_url}/{code}?{query}"]
        return [f"{self.base_url}/entgelte/{code}?{query}"]

    def _load_or_request(self, url: str) -> dict[str, Any]:
        cache_path = self._cache_path(url)
        if cache_path.exists():
            try:
                return json.loads(cache_path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError):
                pass

        elapsed = time.monotonic() - self._last_request_at
        if elapsed < self.min_request_interval_seconds:
            time.sleep(self.min_request_interval_seconds - elapsed)

        request = urllib.request.Request(
            url,
            headers=self._headers(),
            method="GET",
        )
        payload: dict[str, Any]
        try:
            with urllib.request.urlopen(
                request,
                timeout=self.timeout_seconds,
            ) as response:
                response_text = response.read().decode("utf-8", errors="replace")
                payload = {
                    "url": url,
                    "status_code": response.status,
                    "response_text": response_text,
                    "fetched_at": datetime.now(UTC).isoformat(),
                }
        except urllib.error.HTTPError as error:
            response_text = error.read().decode("utf-8", errors="replace")
            payload = {
                "url": url,
                "status_code": error.code,
                "response_text": response_text,
                "fetched_at": datetime.now(UTC).isoformat(),
            }
        except urllib.error.URLError as error:
            payload = {
                "url": url,
                "status_code": 0,
                "response_text": str(error.reason),
                "fetched_at": datetime.now(UTC).isoformat(),
            }
        self._last_request_at = time.monotonic()
        self.request_count += 1
        self.cache_dir.mkdir(parents=True, exist_ok=True)
        cache_path.write_text(
            json.dumps(payload, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
        return payload

    def _cache_path(self, url: str) -> Path:
        stable_hash = hashlib.sha256(url.encode("utf-8")).hexdigest()
        return self.cache_dir / f"{stable_hash}.json"

    def _headers(self) -> dict[str, str]:
        headers = {
            "Accept": "application/json",
            "User-Agent": "career-compass-german-salary-seed/1.0",
        }
        if self.x_api_key:
            headers["X-API-Key"] = self.x_api_key
            headers["x-api-key"] = self.x_api_key
            headers["OAuthAccessToken"] = self.x_api_key
        if self.client_id:
            headers["X-Client-Id"] = self.client_id
        if self.client_secret:
            headers["X-Client-Secret"] = self.client_secret
        return headers

    def _parse_successful_response(
        self,
        response: Mapping[str, Any],
        fallback_title: str,
        attempt: KldbLookupAttempt,
    ) -> SalaryLookupResult:
        response_text = str(response.get("response_text") or "")
        try:
            payload = json.loads(response_text)
        except json.JSONDecodeError:
            return SalaryLookupResult(
                data=None,
                source_status="api_failed",
                notes="Entgeltatlas API returned non-JSON data.",
            )

        salary_data = parse_salary_payload(
            payload,
            fallback_title=fallback_title,
            lookup_code_used=attempt.code,
            lookup_level_used=attempt.level,
            fallback_group_used=attempt.broad_fallback,
        )
        if salary_data is None or salary_data.median_monthly_gross_eur is None:
            return SalaryLookupResult(
                data=None,
                source_status="api_missing",
                notes="Entgeltatlas API returned JSON but no recognizable median salary.",
            )
        source_status = salary_source_status_for_data(salary_data)
        notes = [
            "Salary parsed from cached/API Entgeltatlas response.",
        ]
        if salary_data.fallback_group_used:
            notes.append(f"Broader fallback KldB code {salary_data.lookup_code_used} returned data.")
        if salary_data.salary_value_capped:
            notes.append("Entgeltatlas returned a capped median display value.")
        return SalaryLookupResult(
            data=salary_data,
            source_status=source_status,
            notes=" ".join(notes),
        )


def parse_salary_payload(
    payload: Any,
    fallback_title: str,
    lookup_code_used: str = "",
    lookup_level_used: str = "",
    fallback_group_used: bool = False,
) -> SalaryData | None:
    flattened = list(flatten_payload(payload))

    median_value: int | None = None
    median_display = ""
    salary_value_capped = False
    for key_path, value in flattened:
        key = key_path.casefold()
        if looks_like_median_salary_key(key):
            parsed_value, parsed_display, parsed_capped = parse_salary_value(value)
            if parsed_value is not None:
                median_value = parsed_value
                median_display = parsed_display
                salary_value_capped = parsed_capped
                break

    if median_value is None:
        for _, value in flattened:
            parsed_value, parsed_display, parsed_capped = parse_salary_value(value)
            if parsed_value is not None and 1000 <= parsed_value <= 20000:
                median_value = parsed_value
                median_display = parsed_display
                salary_value_capped = parsed_capped
                break

    if median_value is None:
        return None

    low_value = first_salary_for_key(flattened, ("low", "lower", "p25", "q1", "unten", "unter"))
    high_value = first_salary_for_key(flattened, ("high", "upper", "p75", "q3", "oben", "ober"))
    title = first_text_for_key(flattened, ("title", "titel", "beruf", "bezeichnung")) or fallback_title
    region = first_text_for_key(flattened, ("region", "gebiet", "land")) or "Deutschland"
    data_period = first_text_for_key(flattened, ("period", "datenstand", "jahr", "stand", "stichtag"))
    url = first_text_for_key(flattened, ("url", "link", "href"))

    return SalaryData(
        median_monthly_gross_eur=median_value,
        median_display=median_display or format_int(median_value),
        low_monthly_gross_eur=low_value,
        high_monthly_gross_eur=high_value,
        salary_value_capped=salary_value_capped,
        match_title=title,
        region=region,
        data_period=data_period,
        entgeltatlas_url=url,
        lookup_code_used=lookup_code_used,
        lookup_level_used=lookup_level_used,
        fallback_group_used=fallback_group_used,
    )


